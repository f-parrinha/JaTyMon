#!/usr/bin/env bash
#
# 		gen-monitors.sh
#
# Generates monitors for each use case by executing JaTyMon. The script also verifies whether the
#		tool has changed, or if its output is not always the same. It creates a hash for the content
#		of every java file in the corresponding use case. Then, it generates the monitors and
#		produces a new hash on the new output, comparing it with the older one. Both hashes must be equal. 
#		This script must be executed after build-tool.sh and before build-usecases.sh.
#   
#
# Usage: "bash gen-monitors.sh" (after build-tool.sh, before build-usecases.sh)
# Requires:
#  	- common.sh              
#  	- run-JaTyMon-maven.sh   (generated by build-tool.sh into $JATYMON_OUT)
#
# Environment:
#  	- CONF_LEVEL confidence level	(default 0.95)
#
# Author: Francisco Parrinha
#

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

if [ "$#" -gt 0 ]; then
echo "Usage: $0" >&2
    exit 1
fi

CONF_LEVEL="${CONF_LEVEL:-0.85}"
RUNNER="$JATYMON_OUT/run-JaTyMon-maven.sh"

# Check if the run script generated by the tool build already exists
[ -f "$RUNNER" ] || { echo "[gen-monitors] $RUNNER not found. Run build-tool.sh first" >&2; exit 1; }


# ----------------- METHODS ----------------- #


#
# Hashes with SHA256 the Java contents in a given directory 
#		$1: Directory 
#
hash_dir() {
    (
        cd "$1"
        find . -type f -name '*.java' -print0 |
            while IFS= read -r -d '' file; do
                sha256sum "$file"
            done |
            sort |
            sha256sum |
            cut -d' ' -f1
    )
}


#
# Generates monitors for a given use case given a confidence level
# 		$1: use case folder name
#		$2: confidence level (0 <= l < 1)
#
gen() {
    local uc="$1" conf="$2"
    local dir="$USE_CASES_DIR/$uc"
    local tmp_before tmp_after
    local before after

    tmp_before="$(mktemp -d)"
    tmp_after="$(mktemp)"

    trap 'rm -rf "$tmp_before"; rm -f "$tmp_after"' RETURN

    # Preserve original Java files.
    cp -a "$dir/src/." "$tmp_before/"

    before="$(hash_dir "$dir/src")"

    echo "[gen-monitors] $uc: running JaTyMon (confidence $conf)"
    bash "$RUNNER" "$dir" "$conf"

    after="$(hash_dir "$dir/src")"

    if [ "$before" = "$after" ]; then
        echo "[gen-monitors] $uc: UNCHANGED"
    else
        echo "[gen-monitors] $uc: CHANGED" >&2

        echo "[gen-monitors] File-level differences:" >&2
        diff -qr "$tmp_before" "$dir/src" || true

        echo "[gen-monitors] Content differences:" >&2

        diff -ru "$tmp_before" "$dir/src" || true

        return 1
    fi

    rm -rf "$tmp_before"
    rm -f "$tmp_after"
    trap - RETURN
}


# ----------------- MAIN EXECUTION ----------------- #


failed=0
gen ABD        "$CONF_LEVEL" || failed=1
gen MultiPaxos "$CONF_LEVEL" || failed=1

echo "[gen-monitors] done"
exit "$failed"
